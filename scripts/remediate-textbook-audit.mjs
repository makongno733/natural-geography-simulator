function makeBody(points, source, note) {
  return [
    '## 教学草稿（待教师复核）',
    ...points.map(point => `- ${point}`),
    '',
    '## 来源与边界',
    `依据仓库内人教版教材文本线索「${source}」独立整理，未复制教材原文。${note}本稿不是人工审校结论，不应标注为已核验内容。`
  ].join('\n')
}

for (const [key, remediation] of Object.entries(sections)) {
  const [grade, book, chapter, section] = key.split('|')
  const file = path.join('src/textbook/data', grade, book, 'content.json')
  const data = JSON.parse(await readFile(file, 'utf8'))
  const target = data[chapter]?.sections?.[section]
  if (!target) throw new Error(`Missing textbook section: ${key}`)
  if (target.editorialReview) throw new Error(`Refusing to overwrite an existing review record: ${key}`)

  const relativeSource = path.join('src/textbook/data', grade, book, 'text.txt')
  target.body = makeBody(remediation.points, remediation.source, remediation.note)
  target.keyPoints = remediation.points
  target.conceptDefinitions = {}
  target.editorialReview = {
    status: 'pending-teacher-review',
    source: relativeSource,
    sourceSection: remediation.source,
    note: remediation.note
  }
  await writeFile(file, `${JSON.stringify(data, null, 2)}\n`)
}

