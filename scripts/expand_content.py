# Expanded concept data - generated from section metadata
def expand_section(book_id, chapter_id, section_id, section_data):
    """Generate expanded conceptDefinitions for a section."""
    title = section_data.get('title', '')
    body = section_data.get('body', '')
    keypoints = section_data.get('keyPoints', [])

    # Extract existing concepts to keep
    existing = section_data.get('conceptDefinitions', {}) or {}

    # Build new structure
    new_defs = {}

    # Keep existing groups and concepts
    for group_name, concepts in existing.items():
        if group_name not in new_defs:
            new_defs[group_name] = {}
        for cname, cdef in (concepts or {}).items():
            new_defs[group_name][cname] = cdef

    # Ensure we have core concepts group
    if '核心概念' not in new_defs:
        new_defs['核心概念'] = {}

    # Ensure we have 过程机制 group
    if '过程机制' not in new_defs:
        new_defs['过程机制'] = {}
    if '过程机制' in new_defs and isinstance(new_defs['过程机制'], dict):
        # Convert old combined "过程机制" concept into proper format if needed
        if '过程机制' in new_defs['过程机制']:
            # Already merged; keep for now
            pass

    # Generate missing groups based on book/chapter knowledge
    generate_missing_groups(book_id, chapter_id, section_id, title, body, keypoints, new_defs)

    return new_defs


