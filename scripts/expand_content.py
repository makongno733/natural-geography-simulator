def add_if_missing(defs, group_name, concept_name, senior_def):
    """Add concept to group if it doesn't already exist."""
    if group_name not in defs:
        defs[group_name] = {}
    if concept_name not in defs[group_name]:
        defs[group_name][concept_name] = {
            '初中': senior_def,  # Both levels get same content for now
            '高中': senior_def,
        }


def process_book(book_name):
    """Process a single book's content.json."""
    filepath = os.path.join(DATA_DIR, book_name, 'content.json')
    if not os.path.exists(filepath):
        print(f"  SKIP: {filepath} not found")
        return 0

    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)

    total_added = 0

    for chapter_id, chapter_data in data.items():
        if not isinstance(chapter_data, dict) or 'sections' not in chapter_data:
            continue

        sections = chapter_data.get('sections', {})
        for section_id, section_data in sections.items():
            if not isinstance(section_data, dict):
                continue

            # Count existing concepts before expansion
            existing_defs = section_data.get('conceptDefinitions', {}) or {}
            old_count = sum(len(v) if isinstance(v, dict) else 0 for v in existing_defs.values())

            # Generate expanded definitions
            new_defs = expand_section(book_name, chapter_id, section_id, section_data)

            # Count new concepts
            new_count = sum(len(v) if isinstance(v, dict) else 0 for v in new_defs.values())
            added = new_count - old_count

            if added > 0:
                section_data['conceptDefinitions'] = new_defs
                total_added += added
                print(f"    {chapter_id} {section_id}: {old_count} → {new_count} concepts (+{added})")

    # Write back
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return total_added


def main():
    print("=" * 60)
    print("高中地理教材概念定义批量扩展")
    print("=" * 60)

    grand_total = 0
    for book in BOOKS:
        print(f"\n📘 {book}:")
        added = process_book(book)
        grand_total += added
        print(f"  ✅ {book}: +{added} concepts")

    print(f"\n{'='*60}")
    print(f"🎉 总计新增: {grand_total} concepts")
    print(f"{'='*60}")

    return 0


